#!/usr/bin/env python3
"""Generate CalibrePilot/Certified.lean from stage 1's witness table.

Usage:  lake env lean CalibrePilot/Gen.lean > witnesses.txt
        python3 tools/gen_certified.py witnesses.txt > CalibrePilot/Certified.lean
"""
import sys

CMP = {"lt": "(fun a b => decide (a < b))", "le": "(fun a b => decide (a ≤ b))",
       "gt": "(fun a b => decide (a > b))", "ge": "(fun a b => decide (a ≥ b))",
       "eq": "(fun a b => decide (a = b))", "ne": "(fun a b => decide (a ≠ b))"}
EQ   = {"eq": "(fun a b => decide (a = b))", "ne": "(fun a b => decide (a ≠ b))",
        "false": "(fun _ _ => false)"}
POST = {"id": "id", "rev": "List.reverse", "dropLast": "List.dropLast", "tail": "List.tail"}
DX   = {"id": "id", "succ": "(fun n => n + 1)"}

PREAMBLE = r'''/-
  CALIBRE pilot, stage 2 — GENERATED by tools/gen_certified.py. Do not edit.

  Each rejection is a machine-checked refutation: a proof that the mutant
  violates the specification. Witnesses are found by differential execution in
  Gen.lean; certification here is by proof. `decide` is used rather than
  `native_decide`, so no extra axiom enters any footprint.
-/

namespace CalibreCertified

def Sorted : List Nat → Bool
  | []          => true
  | [_]         => true
  | a :: b :: t => a < b && Sorted (b :: t)

abbrev Impl := Nat → List Nat → List Nat

def insG (cmp eqf : Nat → Nat → Bool) (dx : Nat → Nat) : Nat → List Nat → List Nat
  | x, []     => [dx x]
  | x, a :: t => if cmp (dx x) a then dx x :: a :: t
                 else if eqf (dx x) a then a :: t
                 else a :: insG cmp eqf dx x t

def mk (cmp eqf : Nat → Nat → Bool) (post : List Nat → List Nat) (dx : Nat → Nat) : Impl :=
  fun x l => post (insG cmp eqf dx x l)

/-- The reference, written directly; definitionally the identity member of the
    operator family (`mk lt eq id id`). -/
def ins (x : Nat) : List Nat → List Nat
  | []     => [x]
  | a :: t => if x < a then x :: a :: t
              else if x = a then a :: t
              else a :: ins x t

/-- The strong specification's body: sortedness, no new elements, nothing lost,
    and the inserted value present. -/
def SpecCore (f : Impl) (x : Nat) (l : List Nat) : Bool :=
  Sorted (f x l) &&
  (f x l).all (fun y => y == x || l.contains y) &&
  l.all (fun y => (f x l).contains y) &&
  (f x l).contains x

/-- The strong specification as a proposition over ALL inputs. -/
def SpecStrong (f : Impl) : Prop := ∀ x l, Sorted l = true → SpecCore f x l = true

/-! ## A genuinely proved property of the reference, for all inputs -/

theorem ins_contains (x : Nat) (l : List Nat) : (ins x l).contains x = true := by
  induction l with
  | nil => simp [ins]
  | cons a t ih =>
    simp only [ins]
    by_cases h₁ : x < a
    · simp [h₁]
    · by_cases h₂ : x = a
      · simp [h₁, h₂]
      · simp only [if_neg h₁, if_neg h₂, List.contains_cons, Bool.or_eq_true]
        exact Or.inr ih

/-! ## Certified rejections -/
'''

def main() -> int:
    rows = []
    with open(sys.argv[1], encoding="utf-8") as fh:
        for line in fh:
            line = line.strip().strip('"')
            if "@@" not in line or not line.startswith("cmp="):
                continue
            label, strong, _weak = line.split("@@")
            if strong == "NONE":
                continue
            ops = dict(kv.split("=") for kv in label.split())
            rows.append((label, ops, strong))

    out = [PREAMBLE, ""]
    for i, (label, ops, strong) in enumerate(rows):
        x, lst = strong.split(";")
        name = f"mut{i:03d}"
        out.append(f"/-- `{label}` -/")
        out.append(f"def {name} : Impl := mk {CMP[ops['cmp']]} {EQ[ops['eq']]} "
                   f"{POST[ops['post']]} {DX[ops['dx']]}")
        out.append("")
        out.append(f"theorem rej_{i:03d} : ¬ SpecStrong {name} := fun h =>")
        out.append(f"  absurd (h {x} {lst} (by decide)) (by decide)")
        out.append("")

    out.append("/-! ## Count -/")
    out.append("")
    out.append(f'#eval s!"certified refutations : {{{len(rows)}}}"')
    out.append("")
    out.append("#print axioms rej_000")
    out.append(f"#print axioms rej_{len(rows)//2:03d}")
    out.append(f"#print axioms rej_{len(rows)-1:03d}")
    out.append("#print axioms ins_contains")
    out.append("")
    out.append("end CalibreCertified")
    print("\n".join(out))
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
